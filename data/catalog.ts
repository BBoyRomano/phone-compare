export type CatalogFact = SourcedValue<unknown>;

export function factsFor(phone: PhoneRecord): readonly CatalogFact[] {
  return [
    phone.maker,
    phone.model,
    phone.generation,
    phone.formFactor,
    phone.releasedOn,
    phone.originalPrice,
    phone.display.size,
    phone.display.panel,
    phone.display.resolution,
    phone.display.refreshRate,
    phone.display.peakBrightness,
    ...(phone.secondaryDisplay ? [phone.secondaryDisplay] : []),
    phone.weight,
    phone.storage,
    ...(phone.configurations ? [phone.configurations] : []),
    ...(phone.colors ? [phone.colors] : []),
    ...(phone.dimensions ? [phone.dimensions] : []),
    ...(phone.charging ? [phone.charging] : []),
    phone.processor,
    phone.rearCameras,
    phone.batteryClaim,
    phone.resistance
  ];
}

export function validateCatalog(): string[] {
  const errors: string[] = [];
  const sourceIds = new Set(Object.keys(sources));
  const slugs = new Set<string>();

  for (const [sourceKey, source] of Object.entries(sources)) {
    const sourceId = source.id;
    if (sourceId !== sourceKey) errors.push(`${sourceId}: source key and id must match`);
    if (!source.url.startsWith("https://")) errors.push(`${sourceId}: source URL must use HTTPS`);
    try {
      new URL(source.url);
    } catch {
      errors.push(`${sourceId}: source URL must be valid`);
    }
    if (!source.accessedAt) errors.push(`${sourceId}: access date is required`);
  }

  for (const phone of phones) {
    if (slugs.has(phone.slug)) errors.push(`${phone.slug}: duplicate phone slug`);
    slugs.add(phone.slug);

    const isFoldable = phone.formFactor.value === "book-fold" || phone.formFactor.value === "flip-fold";
    const secondaryDisplay = "secondaryDisplay" in phone ? phone.secondaryDisplay : undefined;
    if (isFoldable && !secondaryDisplay) errors.push(`${phone.slug}: foldable phone lacks a sourced secondary display`);
    if (!isFoldable && secondaryDisplay) errors.push(`${phone.slug}: non-foldable phone has a secondary display`);

    const storage = phone.storage.value;
    if (!Number.isInteger(storage.startsAtGb) || storage.startsAtGb <= 0) {
      errors.push(`${phone.slug}: starting storage must be a positive whole number of GB`);
    }
    if (!storage.options.startsWith(`${storage.startsAtGb} GB`)) {
      errors.push(`${phone.slug}: normalized starting storage does not match the sourced option text`);
    }

    const timingBasis = "basis" in phone.releasedOn ? phone.releasedOn.basis : "availability";
    const timingQualification = "qualification" in phone.releasedOn ? phone.releasedOn.qualification : undefined;
    if (timingBasis === "announcement" && !timingQualification) {
      errors.push(`${phone.slug}: announcement-based launch timing requires an explicit qualification`);
    }

    for (const fact of factsFor(phone)) {
      if (fact.sourceIds.length === 0) errors.push(`${phone.slug}: fact has no provenance`);
      for (const sourceId of fact.sourceIds) {
        if (!sourceIds.has(sourceId)) errors.push(`${phone.slug}: unknown source ${sourceId}`);
      }
    }

    const price = phone.originalPrice.value;
    if ((price.amount !== null && price.amount <= 0) || !price.market || !price.configuration) {
      errors.push(`${phone.slug}: original price lacks interpretive context`);
    }
    if (price.amount === null && !phone.originalPrice.qualification) {
      errors.push(`${phone.slug}: missing original price lacks an explicit qualification`);
    }
  }

  return errors;
}
